//
// Слово владельца 2026-09-21: «в локальном хранилище браузера помнить был ли у
// меня успешная регистрация уже или нет и если была то повторно кидать меня на
// кнопку войти». Форма входа теперь открывается по умолчанию; эта метка решает
// только, показывать ли над ней подсказку «впервые здесь? создайте аккаунт».
//
// 🔒 ЭТО УДОБСТВО, А НЕ ЗНАНИЕ: хранилище бывает пустым (инкогнито, очистка,
// запрет сайта), и тогда человек просто увидит подсказку лишний раз. Решений о
// правах на метке не принимается никогда. Каждое обращение — в try/catch:
// Safari в приватном режиме бросает исключение на самом `localStorage`.

const KEY = "fractera.auth.signed-in-here"

export function rememberSignedInHere(): void {
  try { window.localStorage.setItem(KEY, "1") } catch { /* хранилище закрыто — не беда */ }
}

export function signedInHereBefore(): boolean {
  try { return window.localStorage.getItem(KEY) === "1" } catch { return false }
}
