// Какую роль назвать человеку одной строкой.
//
// 🔒 РОЛЬ, КОТОРАЯ ОТВЕЧАЕТ НА ВОПРОС ЧЕЛОВЕКА, А НЕ ПЕРВАЯ ПОПАВШАЯСЯ. ✗ оплачено
// 2026-09-01: стояло `roles[0]`, у владельца 14 ролей, `user` среди них первая по
// порядку выдачи — и экран писал «ваша роль: user» человеку с ролью архитектора.
//
// Порядок: та роль, ради которой сюда пришли (если она есть) → сильнейший тир
// платформы → хоть что-нибудь. Одна функция на тост и на карточку вошедшего:
// две копии этого правила однажды назвали бы человеку разные роли.
export function pickRoleLabel(roles: string[], requireRole?: string | null): string {
  return (
    (requireRole && roles.includes(requireRole) ? requireRole : undefined) ??
    ["architect", "admin"].find((r) => roles.includes(r)) ??
    roles[0] ??
    "user"
  );
}
